package fr.moussax.blightedMC.shared.ui.menu.interaction;

/**
 * Defines the type of click interaction accepted by a menu item.
 */
public enum MenuItemInteraction {

    /**
     * Accepts left-click interactions.
     */
    LEFT_CLICK,

    /**
     * Accepts right-click interactions.
     */
    RIGHT_CLICK,

    /**
     * Accepts middle-click interactions.
     */
    MIDDLE_CLICK,

    /**
     * Accepts any click interaction.
     */
    ANY_CLICK
}
